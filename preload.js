const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('studio', {
  platform: process.platform,
  version: '0.19.1',
  checkClaude: () => ipcRenderer.invoke('cc:check'),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (s) => ipcRenderer.invoke('settings:set', s),
  openWorkspace: () => ipcRenderer.invoke('ws:open'),
  saveMedia: (name, bytes) => ipcRenderer.invoke('media:save', name, bytes),
  pathOf: (file) => { try { return webUtils.getPathForFile(file) || ''; } catch (_) { return ''; } },
  importMedia: (p) => ipcRenderer.invoke('media:import', p),
  findMedia: (names) => ipcRenderer.invoke('media:find', names),
  log: (m) => ipcRenderer.invoke('app:log', m),
  exportVideo: (o) => ipcRenderer.invoke('export:video', o),
  gpStatus: () => ipcRenderer.invoke('gp:status'),
  gpSetClient: (o) => ipcRenderer.invoke('gp:setClient', o),
  gpConnect: () => ipcRenderer.invoke('gp:connect'),
  gpDisconnect: () => ipcRenderer.invoke('gp:disconnect'),
  gpUpload: (o) => ipcRenderer.invoke('gp:upload', o),
  gpUploadImage: (o) => ipcRenderer.invoke('gp:uploadImage', o),
  exportImage: (o) => ipcRenderer.invoke('image:export', o),
  trimVideo: (o) => ipcRenderer.invoke('video:trim', o),
  joinVideos: (o) => ipcRenderer.invoke('video:join', o),
  recoverScan: () => ipcRenderer.invoke('recover:scan'),
  recoverJobs: () => ipcRenderer.invoke('recover:jobs'),
  backupSave: (json) => ipcRenderer.invoke('backup:save', json),
  exportDir: () => ipcRenderer.invoke('export:dir'),
  openExportDir: () => ipcRenderer.invoke('export:open'),
  pickExportDir: () => ipcRenderer.invoke('export:pick'),
  startJob: (job) => ipcRenderer.invoke('job:start', job),
  cancelJob: (id) => ipcRenderer.invoke('job:cancel', id),
  jobResult: (id) => ipcRenderer.invoke('job:result', id),
  runningJobs: () => ipcRenderer.invoke('job:running'),
  onJobEvent: (fn) => ipcRenderer.on('job:event', (_e, m) => fn(m))
});
